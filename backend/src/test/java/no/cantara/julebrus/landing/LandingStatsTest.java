/**
 * The landing page's numbers are generated by tools/to_landing_stats.py. This recomputes them
 * from data/ in Java, independently, so a stale or wrong history-stats.json fails the build,
 * and checks that the generated file holds no person's name.
 */
class LandingStatsTest {

    static final HistoryStats STATS = HistoryStats.load();

    static double weight(Map<String, String> r) {
        String w = r.get("weight").trim();
        return w.isEmpty() ? 1.0 : Double.parseDouble(w);
    }

    static Map<Integer, List<Map<String, String>>> votesByYear() {
        return RepoData.votes().stream().collect(Collectors.groupingBy(r -> Integer.parseInt(r.get("year")), TreeMap::new, Collectors.toList()));
    }

    static HistoryStats.Season season(int year) {
        return STATS.seasons().stream().filter(s -> s.year() == year).findFirst().orElseThrow();
    }

    @Test
    void perSeasonCountsMatchTheVotes() {
        Map<Integer, List<Map<String, String>>> byYear = votesByYear();
        assertThat(STATS.totals().seasonsWithVotes()).isEqualTo(byYear.size()).isEqualTo(12);
        assertThat(STATS.totals().votes()).isEqualTo(RepoData.votes().size());
        byYear.forEach((year, rows) -> {
            HistoryStats.Season s = season(year);
            assertThat(s.votes()).as("votes " + year).isEqualTo(rows.size());
            assertThat(s.voters()).as("voters " + year).isEqualTo(rows.stream().map(r -> r.get("voter")).distinct().count());
            assertThat(s.beers()).as("beers " + year).isEqualTo(rows.stream().map(r -> r.get("beer").trim().toLowerCase()).distinct().count());
            double w = rows.stream().mapToDouble(LandingStatsTest::weight).sum();
            double mean = rows.stream().mapToDouble(r -> Double.parseDouble(r.get("score")) * weight(r)).sum() / w;
            assertThat(s.meanScore()).as("mean " + year).isCloseTo(mean, org.assertj.core.data.Offset.offset(0.006));
        });
    }

    @Test
    void the2016SummaryComesFromTheRankedListAndTheParticipationCounts() {
        List<Map<String, String>> results = RepoData.csv(RepoData.DATA.resolve("results.csv")).stream()
                .filter(r -> r.get("year").equals("2016")).toList();
        List<Map<String, String>> people = RepoData.csv(RepoData.DATA.resolve("participation.csv")).stream()
                .filter(r -> r.get("year").equals("2016")).toList();
        HistoryStats.Season s = season(2016);
        assertThat(s.aggregate()).isTrue();
        assertThat(s.meanScore()).isNull();
        assertThat(s.beers()).isEqualTo(results.size());
        assertThat(s.voters()).isEqualTo(people.size());
        assertThat(s.votes()).isEqualTo(people.stream().mapToInt(r -> Integer.parseInt(r.get("votes_cast"))).sum());
        Map<String, String> best = results.stream().max(Comparator.comparingDouble(r -> Double.parseDouble(r.get("mean_weighted")))).orElseThrow();
        assertThat(s.top()).extracting(HistoryStats.Top::beer).contains(best.get("beer").trim());
        assertThat(STATS.totals().votesIncludingAggregate()).isEqualTo(STATS.totals().votes() + s.votes());
    }

    @Test
    void topBeerIsTheHighestWeightedMeanWithEnoughVotes() {
        votesByYear().forEach((year, rows) -> {
            Map<String, List<Map<String, String>>> beers = rows.stream()
                    .collect(Collectors.groupingBy(r -> r.get("beer").trim().toLowerCase(), LinkedHashMap::new, Collectors.toList()));
            Map<String, Double> means = new LinkedHashMap<>();
            beers.forEach((k, vs) -> {
                double w = vs.stream().mapToDouble(LandingStatsTest::weight).sum();
                if (w > 0 && vs.size() >= STATS.minVotesForTop())
                    means.put(k, vs.stream().mapToDouble(r -> Double.parseDouble(r.get("score")) * weight(r)).sum() / w);
            });
            double best = means.values().stream().mapToDouble(Double::doubleValue).max().orElseThrow();
            Set<String> expected = means.entrySet().stream().filter(e -> Math.abs(e.getValue() - best) < 1e-9).map(Map.Entry::getKey).collect(Collectors.toSet());
            HistoryStats.Season s = season(year);
            assertThat(s.top()).as("top " + year).extracting(t -> t.beer().toLowerCase()).containsExactlyInAnyOrderElementsOf(expected);
            s.top().forEach(t -> {
                assertThat(t.mean()).isCloseTo(best, org.assertj.core.data.Offset.offset(0.006));
                assertThat(t.votes()).isEqualTo(beers.get(t.beer().toLowerCase()).size());
            });
        });
    }

    @Test
    void diceDistributionAndListSizes() throws IOException {
        Map<Integer, Long> dice = RepoData.votes().stream().map(r -> Double.parseDouble(r.get("score")))
                .filter(v -> v == Math.rint(v)).collect(Collectors.groupingBy(Double::intValue, Collectors.counting()));
        for (int i = 1; i <= 6; i++) assertThat(STATS.dice().get(String.valueOf(i)).longValue()).as("dice " + i).isEqualTo(dice.getOrDefault(i, 0L));
        assertThat(STATS.nonIntegerScores()).isEqualTo(RepoData.votes().size() - dice.values().stream().mapToLong(Long::longValue).sum());

        try (Stream<Path> files = Files.list(RepoData.DATA.resolve("vinmonopolet"))) {
            Map<Integer, Integer> lists = files.filter(p -> p.getFileName().toString().matches("\\d{4}\\.csv"))
                    .collect(Collectors.toMap(p -> Integer.parseInt(p.getFileName().toString().substring(0, 4)), p -> RepoData.csv(p).size()));
            assertThat(STATS.vinmonopolet()).hasSize(lists.size());
            STATS.vinmonopolet().forEach(l -> assertThat(l.listings()).as("list " + l.year()).isEqualTo(lists.get(l.year())));
        }
    }

    @Test
    void regularsCountSeasonsAndVotesByNameAsWritten() {
        for (HistoryStats.Regular reg : STATS.regulars()) {
            List<Map<String, String>> rows = RepoData.votes().stream().filter(r -> r.get("beer").trim().equalsIgnoreCase(reg.beer())).toList();
            assertThat(reg.votes()).as(reg.beer()).isEqualTo(rows.size());
            assertThat(reg.years()).as(reg.beer()).containsExactlyElementsOf(rows.stream().map(r -> Integer.parseInt(r.get("year"))).distinct().sorted().toList());
            assertThat(reg.seasons()).isEqualTo(reg.years().size());
        }
    }

    @Test
    void theGeneratedFileHoldsNoPersonsName() throws IOException {
        String json;
        try (InputStream in = HistoryStats.class.getResourceAsStream(HistoryStats.RESOURCE)) {
            json = new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
        Set<String> names = RepoData.personNames();
        assertThat(names).hasSizeGreaterThan(80);
        assertThat(RepoData.namesIn(json, names)).isEmpty();
        assertThat(json).doesNotContain("@").doesNotContain("voter\"").doesNotContain("rater");
    }

    @Test
    void thePageShowsTheRecomputedNumbers() {
        SeasonProperties season = new SeasonProperties(2026, LocalDate.of(2026, 11, 1), LocalDate.of(2026, 12, 23),
                ZoneId.of("Europe/Oslo"), 5, 5, LocalTime.of(18, 0));
        int total = RepoData.votes().size() + season(2016).votes();
        int votes2003 = votesByYear().get(2003).size();
        for (boolean en : new boolean[]{false, true}) {
            Locale locale = en ? Locale.UK : Locale.forLanguageTag("nb-NO");
            String html = LandingPage.render(STATS, season, new SponsorProperties("eXOReaction", "https://exoreaction.com"),
                    new ContactProperties("kontakt@example.org"), null, en, "/");
            assertThat(html).contains("<strong>" + NumberFormat.getIntegerInstance(locale).format(total) + "</strong>");
            assertThat(html).contains("<td>" + votes2003 + "</td>");
            assertThat(html).contains("mailto:kontakt@example.org").contains(en ? "Sponsored by " : "Støttet av ");
        }
        Set<String> seen = new HashSet<>();
        STATS.seasons().forEach(s -> assertThat(seen.add(String.valueOf(s.year()))).isTrue());
    }

    /**
     * Teams, the live reveal, the podium tip and label photos are always described; push notifications
     * only when push is switched on, with the configured nudge time. The tipping rules come from TipScoring.
     */
    @Test
    void thePageDescribesTheSeasonFeaturesInBothLanguages() {
        SeasonProperties season = new SeasonProperties(2026, LocalDate.of(2026, 11, 1), LocalDate.of(2026, 12, 23),
                ZoneId.of("Europe/Oslo"), 5, 5, LocalTime.of(18, 0));
        SponsorProperties sponsor = new SponsorProperties("eXOReaction", "https://exoreaction.com");
        ContactProperties contact = new ContactProperties("kontakt@example.org");
        Set<String> names = RepoData.personNames();
        for (boolean en : new boolean[]{false, true}) {
            String on = LandingPage.render(STATS, season, sponsor, contact, LocalTime.of(17, 0), en, "/");
            String off = LandingPage.render(STATS, season, sponsor, contact, null, en, "/");
            for (String html : List.of(on, off)) {
                if (en) {
                    assertThat(html).contains("Play for your team, tip the podium")
                            .contains("All through Advent").contains("Cantara against Rebel").contains("Cantara, Rebel or both")
                            .contains("unwrapped on every phone in the same second")
                            .contains("Tip the podium").contains("3 points for the right spot, 1 for a podium beer in the wrong spot, 9 is perfect")
                            .contains("closing at midnight before 23\u00a0December")
                            .contains("Make it yours").contains("A photo of the label")
                            .contains("Ask to link your name to your login");
                } else {
                    assertThat(html).contains("Spill for laget ditt, tipp pallen")
                            .contains("Hele adventstiden").contains("Cantara mot Rebel").contains("Cantara, Rebel eller begge")
                            .contains("pakkes scorene opp på alle telefonene i samme sekund")
                            .contains("Tipp pallen").contains("3 poeng for riktig plass, 1 for et øl på pallen på feil plass, 9 er perfekt")
                            .contains("frist ved midnatt før 23.\u00a0desember")
                            .contains("Gjør den til din").contains("Bilde av etiketten")
                            .contains("Be om å koble navnet ditt til innloggingen");
                }
                // "Lag" now means a team, so the table is never called one.
                assertThat(html).doesNotContain("dere er et lag").doesNotContain("i små lag");
                assertThat(RepoData.namesIn(html, names)).as("names in the page").isEmpty();
            }
            assertThat(on).contains(en ? "A nudge from the calendar" : "Et dytt fra kalenderen").contains(en ? "at 17:00" : "klokka 17.00");
            assertThat(off).doesNotContain("A nudge from the calendar").doesNotContain("Et dytt fra kalenderen")
                    .doesNotContain(en ? "notifications" : "varsler");
        }
    }
}
