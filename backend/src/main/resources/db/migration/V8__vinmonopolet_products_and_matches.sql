-- Vinmonopolet's yearly juleøl lists (public product data) and the review of how the
-- tasting votes of 1998-2019 map onto them. The CSVs under data/vinmonopolet/ are loaded
-- at startup by VmpImportService; the human decisions live only here, in vote_matches.
--
-- (year is a reserved word in H2, so the columns are list_year and season_year, as elsewhere.)
--
-- Numbered V8 on purpose: V7 belongs to the label-photo work. Flyway on a database that
-- already has V8 refuses a later-merged V7 unless outOfOrder is set (see CLAUDE.md).

create table vmp_products (
  article_no   varchar(32) primary key,
  name         varchar(300) not null,
  brewery      varchar(300),
  style        varchar(200),
  country      varchar(100),
  region       varchar(100),
  abv_percent  numeric(6,2),
  volume_l     numeric(6,3),
  organic      boolean not null default false,
  first_year   integer,
  last_year    integer
);
create index ix_vmp_products_name on vmp_products(name);

create table vmp_listings (
  id                  bigint generated by default as identity primary key,
  list_year           integer not null,
  article_no          varchar(32),
  name                varchar(300) not null,
  selection           varchar(100),
  price_nok           numeric(10,2),
  abv_percent         numeric(6,2),
  product_article_no  varchar(32),
  link_basis          varchar(16)
);
create index ix_vmp_listings_year_name on vmp_listings(list_year, name);
create index ix_vmp_listings_name on vmp_listings(name);
create index ix_vmp_listings_product on vmp_listings(product_article_no);

create table vote_matches (
  id                   uuid primary key,
  season_year          integer not null,
  vote_beer            varchar(300) not null,
  machine_status       varchar(16) not null,
  machine_method       varchar(40),
  machine_score        numeric(4,2),
  machine_article_no   varchar(32),
  machine_article_options varchar(400),
  machine_product_name varchar(300),
  machine_list_year    varchar(8),
  candidates           varchar(4000),
  decision             varchar(16)
    check (decision in ('CONFIRMED', 'CHOSEN', 'NONE', 'NOT_A_PRODUCT')),
  decision_article_no  varchar(32),
  decision_product_name varchar(300),
  decided_by           uuid references users(id) on delete set null,
  decided_at           timestamp with time zone,
  version              bigint not null default 0,
  constraint uq_vote_matches_year_beer unique (season_year, vote_beer)
);
create index ix_vote_matches_status on vote_matches(machine_status, decision);
create index ix_vote_matches_decision on vote_matches(decision);
